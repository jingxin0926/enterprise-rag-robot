CREATE TABLE IF NOT EXISTS rag_eval_run (
    id CHAR(36) NOT NULL,
    tenant_id VARCHAR(64) NOT NULL,
    dataset_name VARCHAR(255) NOT NULL,
    dataset_checksum CHAR(64) NOT NULL,
    app_version VARCHAR(64) NOT NULL DEFAULT 'unknown',
    git_commit VARCHAR(64) NOT NULL DEFAULT 'unknown',
    retrieval_config JSON NOT NULL,
    status VARCHAR(32) NOT NULL,
    total INT UNSIGNED NOT NULL DEFAULT 0,
    knowledge_cases INT UNSIGNED NOT NULL DEFAULT 0,
    refusal_cases INT UNSIGNED NOT NULL DEFAULT 0,
    source_exact_match_rate DECIMAL(8,4) NOT NULL DEFAULT 0,
    source_recall DECIMAL(8,4) NOT NULL DEFAULT 0,
    source_precision DECIMAL(8,4) NOT NULL DEFAULT 0,
    answer_point_coverage DECIMAL(8,4) NOT NULL DEFAULT 0,
    refusal_accuracy DECIMAL(8,4) NOT NULL DEFAULT 0,
    average_latency_ms DECIMAL(10,2) NOT NULL DEFAULT 0,
    executed_by VARCHAR(64) NOT NULL,
    error_message VARCHAR(1000) NOT NULL DEFAULT '',
    started_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at DATETIME NULL,
    create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    deleted TINYINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    KEY idx_eval_run_tenant_created (tenant_id, create_time, deleted),
    KEY idx_eval_run_tenant_status (tenant_id, status, deleted)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='RAG evaluation run';

CREATE TABLE IF NOT EXISTS rag_eval_case_result (
    id CHAR(36) NOT NULL,
    run_id CHAR(36) NOT NULL,
    case_id VARCHAR(128) NOT NULL,
    category VARCHAR(64) NOT NULL,
    question TEXT NOT NULL,
    should_refuse TINYINT NOT NULL DEFAULT 0,
    answer_status VARCHAR(64) NOT NULL,
    answer TEXT NOT NULL,
    expected_sources JSON NOT NULL,
    actual_sources JSON NOT NULL,
    source_recall DECIMAL(8,4) NOT NULL DEFAULT 0,
    source_precision DECIMAL(8,4) NOT NULL DEFAULT 0,
    source_exact_match TINYINT NOT NULL DEFAULT 0,
    answer_point_coverage DECIMAL(8,4) NOT NULL DEFAULT 0,
    refusal_correct TINYINT NOT NULL DEFAULT 0,
    latency_ms DECIMAL(10,2) NOT NULL DEFAULT 0,
    create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    deleted TINYINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_eval_case_run_case (run_id, case_id),
    KEY idx_eval_case_run (run_id, deleted),
    CONSTRAINT fk_eval_case_run FOREIGN KEY (run_id) REFERENCES rag_eval_run(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='RAG evaluation case result';
